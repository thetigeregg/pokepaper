import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { composeLocalBackendOrigin, resolveLanHost } from './lan-host.mjs';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LOCAL_BACKEND_PORT = 3000;

export const VARIANTS = {
  local: {
    outputPath: resolve(REPO_ROOT, 'src/environments/environment.ios.local.ts'),
    production: false,
  },
  prod: {
    outputPath: resolve(REPO_ROOT, 'src/environments/environment.ios.prod.ts'),
    production: true,
  },
};

/** Gitignored; included by ios/debug.xcconfig and ios/release.xcconfig. */
export const PASSKEY_XCCONFIG_PATH = resolve(REPO_ROOT, 'ios/passkey.xcconfig');

/**
 * Loads .env into process.env if present. A missing .env is fine — most
 * local dev needs no overrides at all, since the LAN host auto-detects.
 */
export function loadDotEnv(envPath = resolve(REPO_ROOT, '.env')) {
  try {
    process.loadEnvFile(envPath);
  } catch (error) {
    if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') {
      return;
    }

    throw error;
  }
}

/**
 * Parses a backend origin from .env. The app prefixes every `/api` and
 * `/images` request with it, so it must be a bare origin: a path (or even a
 * trailing slash) would produce URLs like `https://host//api/...`. Returns
 * the normalized origin (lowercase host, default port dropped).
 */
export function parseBackendOrigin(name, value, { protocols }) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`${name} must be a URL like https://pokepaper.example.com (got "${value}")`);
  }

  if (!protocols.includes(url.protocol)) {
    const allowed = protocols.map((protocol) => protocol.replace(/:$/, '')).join(' or ');
    throw new Error(`${name} must use ${allowed} (got "${value}")`);
  }

  if (url.pathname !== '/' || url.search || url.hash || url.username || url.password) {
    throw new Error(`${name} must be an origin only, without a path (got "${value}")`);
  }

  return url.origin;
}

export function resolveLocalBackendOrigin(envValues = {}, options = {}) {
  const explicitOrigin = envValues.IOS_BACKEND_ORIGIN_LOCAL?.trim();
  if (explicitOrigin) {
    return parseBackendOrigin('IOS_BACKEND_ORIGIN_LOCAL', explicitOrigin, {
      protocols: ['http:', 'https:'],
    });
  }

  const lanHost = resolveLanHost(envValues, options);
  const composed = composeLocalBackendOrigin(lanHost, LOCAL_BACKEND_PORT);

  if (!composed) {
    throw new Error(
      'Unable to auto-detect a LAN IP for the iOS local build. Set IOS_LAN_HOST (or IOS_BACKEND_ORIGIN_LOCAL) in .env — see .env.example.'
    );
  }

  return parseBackendOrigin('The LAN origin (IOS_LAN_HOST or auto-detected)', composed, {
    protocols: ['http:'],
  });
}

/**
 * The prod backend is the public PokePaper origin (the server's
 * PUBLIC_ORIGIN). It must be https and an origin only: the app appends
 * `/api/...` to it, and passkeys only work against the real https domain.
 */
export function resolveProdBackendOrigin(envValues = {}) {
  const explicitOrigin = envValues.IOS_BACKEND_ORIGIN_PROD?.trim();

  if (!explicitOrigin) {
    throw new Error(
      'IOS_BACKEND_ORIGIN_PROD is required to build the ios-prod environment. Set it in .env to the public origin (the server PUBLIC_ORIGIN) — see .env.example.'
    );
  }

  return parseBackendOrigin('IOS_BACKEND_ORIGIN_PROD', explicitOrigin, { protocols: ['https:'] });
}

export function buildEnvironmentIosSource({ production, apiUrl }) {
  return `// Generated by scripts/write-environment-ios.mjs — do not edit.
// Re-run npm run build:ios:local (or build:ios:prod) after changing backend origin env vars.

export const environment = {
  production: ${String(production)},
  apiUrl: '${apiUrl.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',
};
`;
}

/**
 * The domain for the app's `webcredentials:` associated-domains entitlement:
 * the relying party the server's passkeys are bound to. Defaults to the host
 * of IOS_BACKEND_ORIGIN_PROD (the server's RP_ID defaults to its
 * PUBLIC_ORIGIN host too); IOS_PASSKEY_DOMAIN overrides it when the server
 * sets a different RP_ID. Returns null when neither is set: local builds
 * don't need passkeys (the LAN server runs with AUTH_DEV_BYPASS), so that
 * only matters for prod builds, which already require the origin.
 */
export function resolvePasskeyDomain(envValues = {}) {
  const explicitDomain = envValues.IOS_PASSKEY_DOMAIN?.trim().toLowerCase();
  if (explicitDomain) {
    if (!/^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/.test(explicitDomain)) {
      throw new Error(
        `IOS_PASSKEY_DOMAIN must be a hostname like pokepaper.example.com (got "${explicitDomain}")`
      );
    }
    return explicitDomain;
  }

  if (!envValues.IOS_BACKEND_ORIGIN_PROD?.trim()) {
    return null;
  }

  return new URL(resolveProdBackendOrigin(envValues)).hostname;
}

export function buildPasskeyXcconfigSource(domain) {
  return `// Generated by scripts/write-environment-ios.mjs — do not edit.
// The associated-domains entitlement reads this (webcredentials:$(PASSKEY_DOMAIN)).
PASSKEY_DOMAIN = ${domain ?? ''}
`;
}

export function generatePasskeyXcconfig({
  envValues = process.env,
  outputPath = PASSKEY_XCCONFIG_PATH,
  writeFileSyncFn = writeFileSync,
} = {}) {
  const domain = resolvePasskeyDomain(envValues);
  writeFileSyncFn(outputPath, buildPasskeyXcconfigSource(domain), 'utf8');
  return { outputPath, domain };
}

export function generateEnvironmentIos({
  variant,
  envValues = process.env,
  options = {},
  writeFileSyncFn = writeFileSync,
  variants = VARIANTS,
} = {}) {
  const config = variants[variant];

  if (!config) {
    throw new Error(`Unknown iOS environment variant: ${String(variant)}`);
  }

  const apiUrl =
    variant === 'local'
      ? resolveLocalBackendOrigin(envValues, options)
      : resolveProdBackendOrigin(envValues);

  const source = buildEnvironmentIosSource({ production: config.production, apiUrl });
  writeFileSyncFn(config.outputPath, source, 'utf8');

  return { outputPath: config.outputPath, apiUrl, source };
}

function main() {
  const variant = process.argv[2];

  if (variant !== 'local' && variant !== 'prod') {
    console.error(
      '[write-environment-ios] Usage: node scripts/write-environment-ios.mjs <local|prod>'
    );
    process.exit(1);
  }

  loadDotEnv();

  try {
    const result = generateEnvironmentIos({ variant });
    console.log(
      `[write-environment-ios] Wrote ${result.outputPath.replace(`${REPO_ROOT}/`, '')} (apiUrl: ${result.apiUrl})`
    );
    const passkey = generatePasskeyXcconfig();
    console.log(
      passkey.domain
        ? `[write-environment-ios] Wrote ${passkey.outputPath.replace(`${REPO_ROOT}/`, '')} (passkey domain: ${passkey.domain})`
        : `[write-environment-ios] Wrote ${passkey.outputPath.replace(`${REPO_ROOT}/`, '')} without a passkey domain (set IOS_BACKEND_ORIGIN_PROD to sign in with passkeys)`
    );
  } catch (error) {
    console.error(
      `[write-environment-ios] ${error instanceof Error ? error.message : String(error)}`
    );
    process.exit(1);
  }
}

const entrypoint = process.argv[1];
if (entrypoint && import.meta.url === pathToFileURL(resolve(entrypoint)).href) {
  main();
}
