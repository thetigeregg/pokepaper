import assert from 'node:assert/strict';
import test from 'node:test';

import {
  PASSKEY_XCCONFIG_PATH,
  VARIANTS,
  buildEnvironmentIosSource,
  buildPasskeyXcconfigSource,
  generateEnvironmentIos,
  generatePasskeyXcconfig,
  resolvePasskeyDomain,
  resolveLocalBackendOrigin,
  resolveProdBackendOrigin,
} from './write-environment-ios.mjs';

test('resolveLocalBackendOrigin prefers IOS_BACKEND_ORIGIN_LOCAL when set', () => {
  const origin = resolveLocalBackendOrigin({
    IOS_BACKEND_ORIGIN_LOCAL: 'http://10.0.0.5:9999',
  });

  assert.equal(origin, 'http://10.0.0.5:9999');
});

test('resolveLocalBackendOrigin composes from auto-detected LAN host + fixed port 3000', () => {
  const origin = resolveLocalBackendOrigin(
    {},
    {
      networkInterfaces: () => ({
        en0: [{ family: 'IPv4', internal: false, address: '192.168.1.50' }],
      }),
    }
  );

  assert.equal(origin, 'http://192.168.1.50:3000');
});

test('resolveLocalBackendOrigin throws a clear error when no LAN host can be found', () => {
  assert.throws(
    () =>
      resolveLocalBackendOrigin(
        {},
        {
          networkInterfaces: () => ({
            lo0: [{ family: 'IPv4', internal: true, address: '127.0.0.1' }],
          }),
        }
      ),
    /Unable to auto-detect a LAN IP/
  );
});

test('resolveProdBackendOrigin returns IOS_BACKEND_ORIGIN_PROD', () => {
  const origin = resolveProdBackendOrigin({
    IOS_BACKEND_ORIGIN_PROD: ' https://prod.example.com ',
  });

  assert.equal(origin, 'https://prod.example.com');
});

test('resolveProdBackendOrigin drops a trailing slash', () => {
  const origin = resolveProdBackendOrigin({ IOS_BACKEND_ORIGIN_PROD: 'https://prod.example.com/' });

  assert.equal(origin, 'https://prod.example.com');
});

test('resolveProdBackendOrigin throws a clear error when IOS_BACKEND_ORIGIN_PROD is unset', () => {
  assert.throws(() => resolveProdBackendOrigin({}), /IOS_BACKEND_ORIGIN_PROD is required/);
  assert.throws(
    () => resolveProdBackendOrigin({ IOS_BACKEND_ORIGIN_PROD: '   ' }),
    /IOS_BACKEND_ORIGIN_PROD is required/
  );
});

test('resolveLocalBackendOrigin normalizes IOS_BACKEND_ORIGIN_LOCAL', () => {
  assert.equal(
    resolveLocalBackendOrigin({ IOS_BACKEND_ORIGIN_LOCAL: 'http://192.168.1.50:3000/' }),
    'http://192.168.1.50:3000'
  );
});

test('resolveLocalBackendOrigin rejects an IOS_BACKEND_ORIGIN_LOCAL with a path', () => {
  assert.throws(
    () => resolveLocalBackendOrigin({ IOS_BACKEND_ORIGIN_LOCAL: 'http://192.168.1.50:3000/api' }),
    /IOS_BACKEND_ORIGIN_LOCAL must be an origin only/
  );
});

test('resolveLocalBackendOrigin rejects a non-http IOS_BACKEND_ORIGIN_LOCAL', () => {
  assert.throws(
    () => resolveLocalBackendOrigin({ IOS_BACKEND_ORIGIN_LOCAL: 'ftp://192.168.1.50' }),
    /must use http or https/
  );
});

test('resolveLocalBackendOrigin brackets an IPv6 IOS_LAN_HOST', () => {
  assert.equal(resolveLocalBackendOrigin({ IOS_LAN_HOST: 'fe80::1' }), 'http://[fe80::1]:3000');
});

test('resolveProdBackendOrigin normalizes case and the default port', () => {
  assert.equal(
    resolveProdBackendOrigin({ IOS_BACKEND_ORIGIN_PROD: 'https://PokePaper.Example.com:443' }),
    'https://pokepaper.example.com'
  );
});

test('resolveProdBackendOrigin rejects origins with a query or hash', () => {
  for (const value of ['https://prod.example.com/?x=1', 'https://prod.example.com/#top']) {
    assert.throws(
      () => resolveProdBackendOrigin({ IOS_BACKEND_ORIGIN_PROD: value }),
      /origin only/,
      value
    );
  }
});

test('resolveProdBackendOrigin rejects values that are not URLs', () => {
  assert.throws(
    () => resolveProdBackendOrigin({ IOS_BACKEND_ORIGIN_PROD: 'prod.example.com' }),
    /must be a URL/
  );
});

test('resolveProdBackendOrigin rejects non-https origins', () => {
  assert.throws(
    () => resolveProdBackendOrigin({ IOS_BACKEND_ORIGIN_PROD: 'http://prod.example.com' }),
    /must use https/
  );
});

test('resolveProdBackendOrigin rejects origins with a path', () => {
  assert.throws(
    () => resolveProdBackendOrigin({ IOS_BACKEND_ORIGIN_PROD: 'https://prod.example.com/app' }),
    /origin only/
  );
});

test('buildEnvironmentIosSource emits a minimal generated environment file', () => {
  const source = buildEnvironmentIosSource({
    production: false,
    apiUrl: 'http://192.168.1.50:3000',
  });

  assert.match(source, /Generated by scripts\/write-environment-ios\.mjs — do not edit\./);
  assert.match(source, /production: false,/);
  assert.match(source, /apiUrl: 'http:\/\/192\.168\.1\.50:3000',/);
});

test('buildEnvironmentIosSource escapes quotes and backslashes', () => {
  const source = buildEnvironmentIosSource({ production: false, apiUrl: "http://a'b\\c" });

  assert.ok(source.includes("apiUrl: 'http://a\\'b\\\\c',"), source);
});

test('generateEnvironmentIos writes the local variant to its output path', () => {
  let written = null;
  const result = generateEnvironmentIos({
    variant: 'local',
    envValues: { IOS_BACKEND_ORIGIN_LOCAL: 'http://192.168.1.50:3000' },
    writeFileSyncFn: (path, contents) => {
      written = { path, contents };
    },
  });

  assert.equal(result.outputPath, VARIANTS.local.outputPath);
  assert.equal(written.path, VARIANTS.local.outputPath);
  assert.match(written.contents, /apiUrl: 'http:\/\/192\.168\.1\.50:3000',/);
  assert.match(written.contents, /production: false,/);
});

test('generateEnvironmentIos writes the prod variant to its output path', () => {
  let written = null;
  const result = generateEnvironmentIos({
    variant: 'prod',
    envValues: { IOS_BACKEND_ORIGIN_PROD: 'https://prod.example.com' },
    writeFileSyncFn: (path, contents) => {
      written = { path, contents };
    },
  });

  assert.equal(result.outputPath, VARIANTS.prod.outputPath);
  assert.match(written.contents, /apiUrl: 'https:\/\/prod\.example\.com',/);
  assert.match(written.contents, /production: true,/);
});

test('generateEnvironmentIos rejects an unknown variant', () => {
  assert.throws(
    () => generateEnvironmentIos({ variant: 'staging' }),
    /Unknown iOS environment variant/
  );
});

test('resolvePasskeyDomain uses the prod origin host by default', () => {
  assert.equal(
    resolvePasskeyDomain({ IOS_BACKEND_ORIGIN_PROD: 'https://PokePaper.Example.com' }),
    'pokepaper.example.com'
  );
});

test('resolvePasskeyDomain prefers IOS_PASSKEY_DOMAIN', () => {
  assert.equal(
    resolvePasskeyDomain({
      IOS_BACKEND_ORIGIN_PROD: 'https://pokepaper.example.com',
      IOS_PASSKEY_DOMAIN: ' Example.com ',
    }),
    'example.com'
  );
});

test('resolvePasskeyDomain returns null when no domain is configured', () => {
  assert.equal(resolvePasskeyDomain({}), null);
  assert.equal(resolvePasskeyDomain({ IOS_BACKEND_ORIGIN_PROD: '  ' }), null);
});

test('resolvePasskeyDomain rejects invalid values', () => {
  for (const value of ['not a domain', 'localhost', 'https://example.com', 'example.com/x']) {
    assert.throws(
      () => resolvePasskeyDomain({ IOS_PASSKEY_DOMAIN: value }),
      /IOS_PASSKEY_DOMAIN must be a hostname/,
      value
    );
  }
  assert.throws(
    () => resolvePasskeyDomain({ IOS_BACKEND_ORIGIN_PROD: 'http://pokepaper.example.com' }),
    /must use https/
  );
});

test('buildPasskeyXcconfigSource sets PASSKEY_DOMAIN, empty without a domain', () => {
  assert.match(
    buildPasskeyXcconfigSource('pokepaper.example.com'),
    /^PASSKEY_DOMAIN = pokepaper\.example\.com$/m
  );
  assert.match(buildPasskeyXcconfigSource(null), /^PASSKEY_DOMAIN = $/m);
});

test('generatePasskeyXcconfig writes the gitignored xcconfig', () => {
  let written = null;
  const result = generatePasskeyXcconfig({
    envValues: { IOS_BACKEND_ORIGIN_PROD: 'https://pokepaper.example.com' },
    writeFileSyncFn: (path, contents) => {
      written = { path, contents };
    },
  });

  assert.equal(result.domain, 'pokepaper.example.com');
  assert.equal(written.path, PASSKEY_XCCONFIG_PATH);
  assert.match(PASSKEY_XCCONFIG_PATH, /ios\/passkey\.xcconfig$/);
  assert.match(written.contents, /PASSKEY_DOMAIN = pokepaper\.example\.com/);
});
